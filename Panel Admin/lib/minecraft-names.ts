export type ParsedItem = {
  slot: number
  id: string
  name: string
  customName: string | null
  count: number
  damage: number | null
  maxDamage: number | null
  durabilityPct: number | null
  textureUrl: string
  enchantments: ParsedEnchantment[]
  isEnchanted: boolean
  trim: { pattern: string; material: string } | null
  repairCost: number | null
  lore: string[]
}

export function parseNbtItem(rawItem: any, fallbackSlot = 0): ParsedItem | null {
  if (!rawItem || !rawItem.id) return null
  const id = String(rawItem.id)
  const count = Number(rawItem.count ?? rawItem.Count ?? 1)
  const slot = Number(rawItem.Slot ?? fallbackSlot)

  // Durability & damage
  let damage: number | null = null
  if (rawItem.components && typeof rawItem.components['minecraft:damage'] === 'number') {
    damage = rawItem.components['minecraft:damage']
  } else if (rawItem.tag && typeof rawItem.tag.Damage === 'number') {
    damage = rawItem.tag.Damage
  }

  const maxDamage = ITEM_MAX_DURABILITY[id] || null
  let durabilityPct: number | null = null
  if (damage !== null && maxDamage !== null) {
    durabilityPct = Math.max(0, Math.min(100, Math.round(((maxDamage - damage) / maxDamage) * 100)))
  }

  // Enchantments
  const enchantments = parseEnchantmentsFromNbt(rawItem)
  const isEnchanted = enchantments.length > 0 || id === 'minecraft:enchanted_golden_apple'

  // Custom name
  let customName: string | null = null
  if (rawItem.components) {
    const rawName = rawItem.components['minecraft:custom_name'] || rawItem.components['minecraft:item_name']
    if (typeof rawName === 'string') {
      try {
        const parsedJson = JSON.parse(rawName)
        customName = typeof parsedJson === 'object' && parsedJson.text ? parsedJson.text : String(parsedJson)
      } catch {
        customName = rawName.replace(/^"/, '').replace(/"$/, '')
      }
    }
  } else if (rawItem.tag?.display?.Name) {
    try {
      const parsedJson = JSON.parse(rawItem.tag.display.Name)
      customName = typeof parsedJson === 'object' && parsedJson.text ? parsedJson.text : String(parsedJson)
    } catch {
      customName = String(rawItem.tag.display.Name)
    }
  }

  // Trim
  let trim: { pattern: string; material: string } | null = null
  if (rawItem.components?.['minecraft:trim']) {
    const t = rawItem.components['minecraft:trim']
    trim = {
      material: String(t.material || '').replace(/^minecraft:/, ''),
      pattern: String(t.pattern || '').replace(/^minecraft:/, ''),
    }
  }

  // Repair cost
  let repairCost: number | null = null
  if (rawItem.components && typeof rawItem.components['minecraft:repair_cost'] === 'number') {
    repairCost = rawItem.components['minecraft:repair_cost']
  } else if (rawItem.tag && typeof rawItem.tag.RepairCost === 'number') {
    repairCost = rawItem.tag.RepairCost
  }

  // Lore
  const lore: string[] = []
  const rawLore = rawItem.components?.['minecraft:lore'] || rawItem.tag?.display?.Lore
  if (Array.isArray(rawLore)) {
    for (const l of rawLore) {
      if (typeof l === 'string') {
        try {
          const parsed = JSON.parse(l)
          lore.push(typeof parsed === 'object' && parsed.text ? parsed.text : String(parsed))
        } catch {
          lore.push(l)
        }
      }
    }
  }

  return {
    slot,
    id,
    name: translateMinecraft(id),
    customName,
    count,
    damage,
    maxDamage,
    durabilityPct,
    textureUrl: getItemTextureUrl(id),
    enchantments,
    isEnchanted,
    trim,
    repairCost,
    lore,
  }
}


export function toRomanNumeral(num: number): string {
  if (num <= 0) return ''
  const lookup: [string, number][] = [
    ['X', 10],
    ['IX', 9],
    ['V', 5],
    ['IV', 4],
    ['I', 1],
  ]
  let roman = ''
  let n = num
  for (const [letter, val] of lookup) {
    while (n >= val) {
      roman += letter
      n -= val
    }
  }
  return roman || String(num)
}

export function translateEnchantment(rawId: string): string {
  if (!rawId) return 'Encantamiento'
  const clean = rawId.replace(/^minecraft:/, '').toLowerCase()
  if (MINECRAFT_ENCHANTMENTS_ES[clean]) {
    return MINECRAFT_ENCHANTMENTS_ES[clean]
  }
  return clean
    .replace(/_/g, ' ')
    .replace(/\b\w/g, (l) => l.toUpperCase())
}

export function formatEnchantment(rawId: string, level: number): string {
  const name = translateEnchantment(rawId)
  if (level <= 1 && ['mending', 'silk_touch', 'infinity', 'channeling', 'multishot', 'aqua_affinity'].some(e => rawId.includes(e))) {
    // Single-level enchantments in vanilla usually display without Roman numeral I
    return name
  }
  const roman = toRomanNumeral(level)
  return roman ? `${name} ${roman}` : name
}

export type ParsedEnchantment = {
  id: string
  name: string
  level: number
  formatted: string
}

export function parseEnchantmentsFromNbt(rawItem: any): ParsedEnchantment[] {
  const enchantments: ParsedEnchantment[] = []
  if (!rawItem) return enchantments

  // 1. Modern Minecraft 1.20.5+ / 1.21+ components
  const comp = rawItem.components
  if (comp) {
    const rawEnch = comp['minecraft:enchantments'] || comp['minecraft:stored_enchantments']
    if (rawEnch) {
      const levels = typeof rawEnch.levels === 'object' && rawEnch.levels !== null ? rawEnch.levels : rawEnch
      if (typeof levels === 'object' && levels !== null) {
        for (const [enchId, lvl] of Object.entries(levels)) {
          if (typeof lvl === 'number' && lvl > 0) {
            const cleanId = String(enchId)
            enchantments.push({
              id: cleanId,
              name: translateEnchantment(cleanId),
              level: lvl,
              formatted: formatEnchantment(cleanId, lvl),
            })
          }
        }
      }
    }
  }

  // 2. Legacy pre-1.20.5 NBT tags
  const tag = rawItem.tag
  if (tag) {
    const legacyList = tag.Enchantments || tag.StoredEnchantments
    if (Array.isArray(legacyList)) {
      for (const e of legacyList) {
        const rawId = String(e.id || '')
        const lvl = Number(e.lvl ?? 1)
        if (rawId && lvl > 0) {
          enchantments.push({
            id: rawId,
            name: translateEnchantment(rawId),
            level: lvl,
            formatted: formatEnchantment(rawId, lvl),
          })
        }
      }
    }
  }

  return enchantments
}

export function translateMinecraft(rawId: string): string {
  if (!rawId) return 'Desconocido'
  const clean = rawId.replace(/^minecraft:/, '').toLowerCase()
  if (MINECRAFT_TRANSLATIONS_ES[clean]) {
    return MINECRAFT_TRANSLATIONS_ES[clean]
  }
  // Title case fallback
  return clean
    .replace(/_/g, ' ')
    .replace(/\b\w/g, (l) => l.toUpperCase())
}

export function getItemTextureUrl(rawId: string): string {
  if (!rawId) return ''
  const clean = rawId.replace(/^minecraft:/, '').toLowerCase()
  return `https://assets.mcasset.cloud/1.21.1/assets/minecraft/textures/item/${clean}.png`
}

export function getBlockTextureUrl(rawId: string): string {
  if (!rawId) return ''
  const clean = rawId.replace(/^minecraft:/, '').toLowerCase()
  return `https://assets.mcasset.cloud/1.21.1/assets/minecraft/textures/block/${clean}.png`
}

